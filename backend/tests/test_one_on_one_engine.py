"""The Python engine must replay the client's attacks bit for bit: the shared
fixture is generated by frontend/src/lib/oneOnOne/engine.fixture.test.ts
(scripted fingers: weaving, letting go, feints at different distances,
shots of every kind, no shot at all)."""

import json
from pathlib import Path

import pytest

from app.services.free_kick_3d_engine import Swipe
from app.services.one_on_one_engine import (
    MAX_RUN_TICKS,
    Timeline,
    create_episode,
    replay_episode,
)

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "one_on_one_episodes.json").read_text())


def _timeline(tl: dict) -> Timeline:
    shot = tl["shot"]
    feint = tl["feint"]
    return Timeline(
        controls=[tuple(c) for c in tl["controls"]],
        feint=(feint["tick"], feint["dir"]) if feint else None,
        shot=(shot["tick"], Swipe(shot["dx"], shot["dy"], shot["curve"], shot["durationMs"])) if shot else None,
    )


def test_fixture_covers_the_outcomes_and_feints():
    assert {"goal", "save", "tackle", "miss"} <= {c["outcome"] for c in FIXTURE}
    assert {"bit", "read", None} == {c["feint"] for c in FIXTURE}


@pytest.mark.parametrize("case", FIXTURE, ids=lambda c: f"{c['seed']}-{c['rating']}-{c['outcome']}")
def test_replays_the_client_episode_exactly(case):
    r = replay_episode(create_episode(case["seed"], case["rating"]), _timeline(case["timeline"]))
    assert (r.outcome, r.tick, r.feint, r.chip) == (case["outcome"], case["tick"], case["feint"], case["chip"])
    f = case["flight"]
    if f is None:
        assert r.flight is None
        return
    fl = r.flight
    # Exact equality on purpose: any drift would let client and server disagree.
    assert fl.outcome == f["outcome"]
    k = f["keeper"]
    assert (fl.keeper_x, fl.keeper_z, fl.lying_for, fl.spread) == (k["x"], k["z"], k["lyingFor"], k["spread"])
    assert fl.over_y == f["overY"]
    assert fl.events == f["events"]
    end = f["end"]
    assert fl.end_t == end["t"]
    assert fl.end_position == (end["position"]["x"], end["position"]["y"], end["position"]["z"])
    assert fl.end_velocity == (end["velocity"]["x"], end["velocity"]["y"], end["velocity"]["z"])


def test_running_at_him_ends_with_the_keeper_taking_the_ball():
    r = replay_episode(create_episode(5), Timeline(controls=[(0, 1, 0)], feint=None, shot=None))
    assert r.outcome == "tackle"
    assert r.tick < MAX_RUN_TICKS


def test_standing_still_the_chance_is_gone():
    # He comes out only so far: an attacker who never moves loses the moment.
    r = replay_episode(create_episode(5), Timeline(controls=[], feint=None, shot=None))
    assert (r.outcome, r.tick) == ("lost", MAX_RUN_TICKS)


def test_rating_edge_makes_the_run_faster():
    tl = Timeline(controls=[(0, 1, 0)], feint=None, shot=None)
    slow = replay_episode(create_episode(9, 55), tl)
    fast = replay_episode(create_episode(9, 99), tl)
    # The quicker attacker meets the (slower) keeper sooner.
    assert fast.tick < slow.tick


