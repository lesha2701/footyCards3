"""The Python engine must replay the client's shots bit for bit: the shared
fixture is generated by frontend/src/lib/freeKick3d/trajectory.fixture.test.ts
(free kicks, penalty kicks against the bot keeper, the bot's penalties
against the player's dive)."""

import json
from pathlib import Path

import pytest

from app.services.free_kick_3d_engine import (
    Dive,
    Swipe,
    create_penalty_setup,
    create_setup,
    mulberry32,
    penalty_bot_shot,
    player_keeper_setup,
    simulate_shot,
)

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "free_kick_3d_shots.json").read_text())


def _swipe(s: dict) -> Swipe:
    return Swipe(s["dx"], s["dy"], s["curve"], s["durationMs"])


def _replay(case: dict):
    mode = case["mode"]
    if mode == "free_kick":
        return simulate_shot(create_setup(case["seed"], case["rating"]), _swipe(case["swipe"]))
    if mode == "penalty_kick":
        return simulate_shot(create_penalty_setup(case["seed"], case["rating"]), _swipe(case["swipe"]))
    d = case["dive"]
    dive = Dive(d["x"], d["y"], d["reactionMs"]) if d else None
    kind, swipe = penalty_bot_shot(case["seed"], dive)
    assert kind == case["kind"]
    assert (swipe.dx, swipe.dy, swipe.curve, swipe.duration_ms) == tuple(case["swipe"].values())
    return simulate_shot(player_keeper_setup(case["seed"], dive), swipe)


def test_fixture_covers_every_outcome_and_mode():
    assert {c["outcome"] for c in FIXTURE} == {"goal", "save", "wall", "miss"}
    assert {c["mode"] for c in FIXTURE} == {"free_kick", "penalty_kick", "penalty_save"}


@pytest.mark.parametrize("case", FIXTURE, ids=lambda c: f"{c['mode']}-{c['seed']}-{c['swipe']['dx']}/{c['swipe']['dy']}")
def test_replays_the_client_shot_exactly(case):
    result = _replay(case)
    end = case["end"]
    assert result.outcome == case["outcome"]
    assert result.end_t == end["t"]
    # Exact equality on purpose: any drift would let client and server disagree.
    assert result.end_position == (end["position"]["x"], end["position"]["y"], end["position"]["z"])
    assert result.end_velocity == (end["velocity"]["x"], end["velocity"]["y"], end["velocity"]["z"])
    assert result.events == case["events"]


def test_mulberry32_is_in_unit_interval_and_seeded():
    a = mulberry32(5)
    b = mulberry32(5)
    values = [a() for _ in range(200)]
    assert values == [b() for _ in range(200)]
    assert all(0 <= v < 1 for v in values)


def test_higher_rating_slows_the_keeper_a_little():
    assert create_setup(7, 95).keeper_speed < create_setup(7, 75).keeper_speed < create_setup(7, 55).keeper_speed
    assert create_setup(7, 75).wall == create_setup(7, 95).wall


def test_a_dive_before_the_strike_is_punished():
    # The kicker sees an early keeper go and places it the other way.
    for seed in range(1, 200):
        kind, swipe = penalty_bot_shot(seed)
        if kind not in ("low_corner", "side", "top_corner"):
            continue
        side = 1 if swipe.dx > 0 else -1
        _, early = penalty_bot_shot(seed, Dive(side * 2000, 800, -100))
        _, on_time = penalty_bot_shot(seed, Dive(side * 2000, 800, 150))
        assert early.dx == -swipe.dx and on_time.dx == swipe.dx


def test_a_keeper_who_stays_saves_down_the_middle_but_not_the_corners():
    # No swipe: he stays in the middle and still goes for a ball near him.
    seen = set()
    for seed in range(1, 400):
        kind, swipe = penalty_bot_shot(seed)
        if kind not in ("power", "low_corner"):
            continue
        setup = player_keeper_setup(seed, None)
        outcome = simulate_shot(setup, swipe).outcome
        assert outcome == ("save" if kind == "power" else "goal"), (seed, kind, outcome)
        seen.add(kind)
    assert seen == {"power", "low_corner"}
