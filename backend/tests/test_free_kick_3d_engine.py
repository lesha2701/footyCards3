"""The Python engine must replay the client's shots bit for bit: the shared
fixture is generated by frontend/src/lib/freeKick3d/trajectory.fixture.test.ts."""

import json
from pathlib import Path

import pytest

from app.services.free_kick_3d_engine import Swipe, create_setup, mulberry32, simulate_shot

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "free_kick_3d_shots.json").read_text())


def test_fixture_covers_every_outcome():
    assert {c["outcome"] for c in FIXTURE} == {"goal", "save", "wall", "miss"}


@pytest.mark.parametrize("case", FIXTURE, ids=lambda c: f"{c['seed']}-{c['rating']}-{c['swipe']['dx']}/{c['swipe']['dy']}")
def test_replays_the_client_shot_exactly(case):
    s = case["swipe"]
    result = simulate_shot(create_setup(case["seed"], case["rating"]), Swipe(s["dx"], s["dy"], s["curve"], s["durationMs"]))
    end = case["end"]
    assert result.outcome == case["outcome"]
    assert result.end_t == end["t"]
    # Exact equality on purpose: any drift would let client and server disagree.
    assert result.end_position == (end["position"]["x"], end["position"]["y"], end["position"]["z"])
    assert result.end_velocity == (end["velocity"]["x"], end["velocity"]["y"], end["velocity"]["z"])
    assert result.events == case["events"]


def test_mulberry32_is_in_unit_interval_and_seeded():
    a = mulberry32(5)
    b = mulberry32(5)
    values = [a() for _ in range(200)]
    assert values == [b() for _ in range(200)]
    assert all(0 <= v < 1 for v in values)


def test_higher_rating_slows_the_keeper_a_little():
    assert create_setup(7, 95).keeper_speed < create_setup(7, 75).keeper_speed < create_setup(7, 55).keeper_speed
    assert create_setup(7, 75).wall == create_setup(7, 95).wall
